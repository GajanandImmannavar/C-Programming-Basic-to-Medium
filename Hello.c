// Include the standard input-output library.
// This is required to use functions such as printf() and scanf().
#include <stdio.h>

// The main() function is the starting point of the C program.
// int means this function returns an integer value.
int main()
{
    // printf() displays output on the screen.
    // "Hii Guys!" is the text to display.
    // \n moves the cursor to a new line after printing.
    printf("Hii Guys!\n");

    // End the main() function.
    // Return 0 usually indicates successful program execution.
    return 0;
}


